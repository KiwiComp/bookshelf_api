/** Code generated by Hilt and kotlinx.serialization, which is not ours to cover. */
val generatedClasses = listOf(
    "**/Hilt_*",
    "**/*_Factory*",
    "**/*_HiltModules*",
    "**/*_MembersInjector*",
    "**/*_Provide*",
    "**/*\$\$serializer*",
)

data class CoverageLayer(
    val name: String,
    val includes: List<String>,
    val minLine: String,
    val minBranch: String?,
)

/** Receives the app's compiled classes from AGP, which knows where each compiler puts them. */
abstract class CoverageVerificationTask : JacocoCoverageVerification() {
    @get:Internal
    abstract val allJars: ListProperty<RegularFile>

    @get:Internal
    abstract val allDirectories: ListProperty<Directory>
}

jacoco {
    toolVersion = android.testCoverage.jacocoVersion
}

val verifyUnitTestCoverage = tasks.register("verifyUnitTestCoverage") {
    group = "verification"
    description = "Checks the debug unit test coverage of each layer against its threshold."
}

androidComponents {
    onVariants(selector().withName("debug")) { variant ->
        coverageLayers.forEach { layer ->
            val verifyLayer = tasks.register<CoverageVerificationTask>(
                "verify${layer.name}Coverage",
            ) {
                group = "verification"
                description = "Checks the unit test coverage of the ${layer.name} layer."
                val unitTest = tasks.named("testDebugUnitTest")
                dependsOn(unitTest)
                executionData(unitTest.get())
                val includes = layer.includes
                val excludes = generatedClasses
                classDirectories.setFrom(
                    files(allDirectories).asFileTree.matching {
                        include(includes)
                        exclude(excludes)
                    },
                )
                violationRules {
                    rule {
                        limit {
                            counter = "LINE"
                            minimum = BigDecimal(layer.minLine)
                        }
                        layer.minBranch?.let { minBranch ->
                            limit {
                                counter = "BRANCH"
                                minimum = BigDecimal(minBranch)
                            }
                        }
                    }
                }
            }
            variant.artifacts
                .forScope(ScopedArtifacts.Scope.PROJECT)
                .use(verifyLayer)
                .toGet(
                    type = ScopedArtifact.CLASSES,
                    inputJars = CoverageVerificationTask::allJars,
                    inputDirectories = CoverageVerificationTask::allDirectories,
                )
            verifyUnitTestCoverage.configure { dependsOn(verifyLayer) }
        }
    }
}

